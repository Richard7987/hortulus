-- texlua tools/gen_inks.lua > plugin/src/inks.rs
local M = dofile("reference/lua/flora/inks.lua")
local function num(v) return string.format("%.17g", v):find("[.e]") and string.format("%.17g", v) or string.format("%.17g.0", v) end
local function keys(t) local k = {} for n in pairs(t) do k[#k + 1] = n end table.sort(k) return k end
print("//! Pilot iroshizuku ramps measured by madoromi. Generated by tools/gen_inks.lua.\n")
print("pub const RAMPS: &[(&str, &[[f64; 3]])] = &[")
for _, n in ipairs(keys(M.ramps)) do
  local s = {}
  for _, r in ipairs(M.ramps[n]) do s[#s + 1] = "[" .. num(r[1]) .. ", " .. num(r[2]) .. ", " .. num(r[3]) .. "]" end
  print(('    ("%s", &[%s]),'):format(n, table.concat(s, ", ")))
end
print("];\n\npub const GROUPS: &[(&str, &[&str])] = &[")
for _, n in ipairs(keys(M.groups)) do
  local s = {}
  for _, r in ipairs(M.groups[n]) do s[#s + 1] = '"' .. r .. '"' end
  print(('    ("%s", &[%s]),'):format(n, table.concat(s, ", ")))
end
print("];\n\npub const COLOURWAYS: &[(&str, &[(&str, &str)])] = &[")
for _, n in ipairs(keys(M.colourways or {})) do
  local s = {}
  for _, k in ipairs(keys(M.colourways[n])) do s[#s + 1] = ('("%s", "%s")'):format(k, M.colourways[n][k]) end
  print(('    ("%s", &[%s]),'):format(n, table.concat(s, ", ")))
end
print("];")
print("\npub const ORDER: &[&str] = &[")
for _, n in ipairs(M.order) do print(('    "%s",'):format(n)) end
print("];")
